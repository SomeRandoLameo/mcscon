#!/usr/bin/env python3
"""Generates cpp/include/mcscon/blocks_gen.h: per-block flags, exact collision shapes per block state (id<<4|meta) for
ids 0..255 (1.10-1.12.2), and optional names.   usage: gen_blocks.py <data/pc> > cpp/include/mcscon/blocks_gen.h
       gen_blocks.py <data/pc> --rust > src/blocks.rs"""
import json, sys
root = sys.argv[1] + "/1.12"
b = json.load(open(root + "/blocks.json")); cs = json.load(open(root + "/blockCollisionShapes.json"))
flags = [0] * 256; names = [""] * 256; byname = {}
for x in b:
    i = x["id"]; f = 0
    if x["name"] in ("water", "flowing_water", "lava", "flowing_lava"): f |= 2
    if x["transparent"]: f |= 4
    if x["name"] in ("ladder", "vine"): f |= 8
    flags[i] = f; names[i] = x["name"]; byname[x["name"]] = i
shapes = cs["shapes"]; sid = sorted(shapes, key=int)
assert [int(k) for k in sid] == list(range(len(sid)))
boxes = []; table = []
for k in sid:
    table.append((len(boxes), len(shapes[k])))
    for bx in shapes[k]:
        q = [round(c * 32) for c in bx]
        assert all(abs(q[i] / 32 - bx[i]) < 1e-9 for i in range(6)), bx
        boxes.append(q)
perid = [[0] * 16 for _ in range(256)]
for name, v in cs["blocks"].items():
    if name not in byname: continue
    i = byname[name]; perid[i] = [v] * 16 if isinstance(v, int) else (v + [0] * 16)[:16]
uniform = [0xFF] * 256; var = []; varidx = [0] * 256
for i in range(256):
    if len(set(perid[i])) == 1: uniform[i] = perid[i][0]
    else: varidx[i] = len(var); var.append(perid[i])
for i in range(256):
    if uniform[i] == 1: flags[i] |= 1          # Solid: full cube for every meta
    elif uniform[i] != 0xFF and uniform[i] != 0: flags[i] |= 16   # partial collision shape
    elif uniform[i] == 0xFF: flags[i] |= 16
if True:
    r = ["// GENERATED by tools/gen_blocks.py - do not edit",
         "//! Per-block flags and exact collision shapes per block state (id << 4 | meta) for ids 0..255 (1.10-1.12.2).",
         "#![allow(clippy::all)]", "",
         "/// Always a full cube for every meta.", "pub const SOLID: u8 = 1;", "pub const LIQUID: u8 = 2;", "pub const TRANSPARENT: u8 = 4;", "pub const CLIMBABLE: u8 = 8;",
         "/// Has collision, not always a full cube.", "pub const PARTIAL_SHAPE: u8 = 16;",
         "pub static FLAGS: [u8; 256] = [" + ",".join(map(str, flags)) + "];",
         "/// Collision box in 1/32 block units, relative to the block corner.",
         "#[derive(Clone, Copy, Debug)]", "pub struct Box32 { pub x0: i8, pub y0: i8, pub z0: i8, pub x1: i8, pub y1: i8, pub z1: i8 }",
         "pub static BOXES: [Box32; %d] = [%s];" % (len(boxes), ",".join("Box32{x0:%d,y0:%d,z0:%d,x1:%d,y1:%d,z1:%d}" % tuple(q) for q in boxes)),
         "#[derive(Clone, Copy, Debug)]", "pub struct ShapeRef { pub off: u16, pub n: u8 }",
         "pub static SHAPES: [ShapeRef; %d] = [%s];" % (len(table), ",".join("ShapeRef{off:%d,n:%d}" % t for t in table)),
         "/// 0xFF: depends on meta, see SHAPE_OF_META.",
         "static SHAPE_OF_ID: [u8; 256] = [" + ",".join(map(str, uniform)) + "];",
         "static VAR_INDEX: [u8; 256] = [" + ",".join(map(str, varidx)) + "];",
         "static SHAPE_OF_META: [[u8; 16]; %d] = [%s];" % (max(1, len(var)), ",".join("[%s]" % ",".join(map(str, v)) for v in var) if var else "[0; 16]"),
         "/// Shape id for a block state (id << 4 | meta); index into [`SHAPES`] (0 = no collision, 1 = full cube).",
         "pub fn shape_of(state: u16) -> u8 { let id = (state >> 4) as u8; let s = SHAPE_OF_ID[id as usize]; if s != 0xFF { s } else { SHAPE_OF_META[VAR_INDEX[id as usize] as usize][(state & 15) as usize] } }",
         "pub static NAMES: [&str; 256] = [" + ",".join('"%s"' % n for n in names) + "];"]
    print("\n".join(r)); sys.exit(0)
