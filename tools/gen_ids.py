#!/usr/bin/env python3
"""Generates src/ids.rs from PrismarineJS/minecraft-data protocol.json.
usage: gen_ids.py <minecraft-data>/data/pc > src/ids.rs
Version-agnostic packet enums + per-version wire-id tables (no dynamic memory, ~1.5KB total)."""
import json, sys, re
root = sys.argv[1]
# (label, data dir, protocol number)
VERS = [("V1_10", "1.10", 210), ("V1_11", "1.11", 315), ("V1_12", "1.12", 335), ("V1_12_2", "1.12.2", 340)]
# 1.11.1/1.11.2 (316) shares 1.11 tables, 1.12.1 (338) shares 1.12.2 tables
def camel(n): return "".join(p.capitalize() for p in n.split("_"))
def load(d, st, dr):
    p = json.load(open(f"{root}/{d}/protocol.json"))[st][dr]["types"]["packet"]
    return {int(k, 16): n for k, n in p[1][0]["type"][1]["mappings"].items()}
STATES = ["handshaking", "status", "login", "play"]
data = {}
for st in STATES:
    for dr in ("toClient", "toServer"):
        per = {v[0]: load(v[1], st, dr) for v in VERS}
        names = sorted(set().union(*[set(m.values()) for m in per.values()]))
        data[(st, dr)] = (names, per)
        if not names: continue
        e = "".join(w.capitalize() for w in (st, "cb" if dr == "toClient" else "sb"))

if True:
    o = ["// GENERATED by tools/gen_ids.py from minecraft-data - do not edit",
         "//! Version-agnostic packet id enums and per-version wire-id tables.",
         "#![allow(clippy::all)]", "",
         "/// Maps wire ids to version-agnostic ids and back for one protocol table (V1_10, V1_11, V1_12, V1_12_2).",
         "pub struct Tables { pub w2a: &'static [u8], pub a2w: &'static [u8] }", ""]
    for st in STATES:
        for dr in ("toClient", "toServer"):
            names, per = data[(st, dr)]
            if not names: continue
            e = "".join(w.capitalize() for w in (st, "cb" if dr == "toClient" else "sb"))
            up = "".join(("_" + c if c.isupper() else c.upper()) for c in e).lstrip("_")
            up = re.sub(r"_+", "_", up)
            o.append("#[repr(u8)]\n#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub enum %s { %s }" % (e, ", ".join(camel(n) for n in names)))
            o.append("impl %s {" % e)
            o.append("    pub const COUNT: u8 = %d;" % len(names))
            o.append("    pub const ALL: [%s; %d] = [%s];" % (e, len(names), ", ".join("%s::%s" % (e, camel(n)) for n in names)))
            o.append("    pub fn from_u8(v: u8) -> Option<%s> { Self::ALL.get(v as usize).copied() }" % e)
            o.append("    pub const NAMES: [&'static str; %d] = [%s];" % (len(names), ", ".join('"%s"' % camel(n) for n in names)))
            o.append("}")
            for lab, _, _ in VERS:
                m = per[lab]; size = max(m) + 1
                inv = {n: i for i, n in m.items()}
                w2a = [str(names.index(m[i])) if i in m else "0xFF" for i in range(size)]
                a2w = [str(inv[n]) if n in inv else "0xFF" for n in names]
                o.append("static %s_%s_W2A: [u8; %d] = [%s];" % (up, lab.upper(), size, ",".join(w2a)))
                o.append("static %s_%s_A2W: [u8; %d] = [%s];" % (up, lab.upper(), len(names), ",".join(a2w)))
            o.append("pub static %s_TABLES: [Tables; %d] = [%s];" % (up, len(VERS), ", ".join(
                "Tables { w2a: &%s_%s_W2A, a2w: &%s_%s_A2W }" % (up, v[0].upper(), up, v[0].upper()) for v in VERS)))
            o.append("")
    print("\n".join(o))
    sys.exit(0)
